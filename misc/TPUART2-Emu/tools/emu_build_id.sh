#!/bin/sh
#
#  emu_build_id.sh - Writes src/emu_build_id.h with the Git commit of the build.
#
#  Run before every build, by the MCUXpresso pre-build step and by CMake. The
#  first 8 hex digits of the commit go into U_EmuIdentify, so a host can log
#  which build runs on the LPC even when the version was not raised. The
#  header is only rewritten when its content changes, so an unchanged commit
#  does not trigger a rebuild.
#
#  Without Git the id is 0, which a host shows as "unknown".
#
#  This program is free software; you can redistribute it and/or modify
#  it under the terms of the GNU General Public License version 3 as
#  published by the Free Software Foundation.
#

project_dir=$(cd "$(dirname "$0")/.." && pwd)
header="$project_dir/src/emu_build_id.h"

build_id=0
dirty=0
commit=$(git -C "$project_dir" rev-parse HEAD 2>/dev/null)
if [ -n "$commit" ]; then
    build_id=$(printf '%.8s' "$commit")
    # Changes to tracked files of this project make the build differ from the commit.
    if ! git -C "$project_dir" diff --quiet HEAD -- . 2>/dev/null; then
        dirty=1
    fi
fi

content="/* Generated by tools/emu_build_id.sh, do not edit or commit. */
#define TPUART_EMU_BUILD_ID    (0x${build_id}u)
#define TPUART_EMU_BUILD_DIRTY (${dirty})"

if [ ! -f "$header" ] || [ "$(cat "$header")" != "$content" ]; then
    printf '%s\n' "$content" > "$header"
fi
